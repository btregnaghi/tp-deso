-- Script de creacion de tablas
-- Uso: docker exec -i evaluaciones-db psql -U postgres -d evaluaciones < api/src/main/resources/db/schema.sql
-- Se puede correr de nuevo: borra todo y lo vuelve a crear.

-- Extension que usan las busquedas sin acentos (PreguntaRepository, CandidatoRepository)
CREATE EXTENSION IF NOT EXISTS unaccent;

-- Se borran en orden inverso a las FK (primero las tablas que referencian a otras)
DROP TABLE IF EXISTS registro_auditoria    CASCADE;
DROP TABLE IF EXISTS item_opcion           CASCADE;
DROP TABLE IF EXISTS item_pregunta         CASCADE;
DROP TABLE IF EXISTS bloque                CASCADE;
DROP TABLE IF EXISTS cuestionario          CASCADE;
DROP TABLE IF EXISTS evaluacion            CASCADE;
DROP TABLE IF EXISTS candidato             CASCADE;
DROP TABLE IF EXISTS caracteristica_puesto CASCADE;
DROP TABLE IF EXISTS puesto                CASCADE;
DROP TABLE IF EXISTS opcion                CASCADE;
DROP TABLE IF EXISTS pregunta              CASCADE;
DROP TABLE IF EXISTS factor                CASCADE;
DROP TABLE IF EXISTS competencia           CASCADE;
DROP TABLE IF EXISTS empresa               CASCADE;

-- Empresa (entidad Empresa)
CREATE TABLE empresa (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

-- Competencia (entidad Competencia)
CREATE TABLE competencia (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(255) NOT NULL UNIQUE,
    nombre      VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    tipo        VARCHAR(255) NOT NULL
                CHECK (tipo IN ('TECNICA', 'ACTITUDINAL')),
    fecha_baja  DATE
);

-- Factor (entidad Factor). Depende de competencia.
CREATE TABLE factor (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(255) NOT NULL UNIQUE,
    nombre         VARCHAR(255) NOT NULL,
    descripcion    VARCHAR(255),
    nro_orden      INTEGER,
    fecha_baja     DATE,
    competencia_id BIGINT       NOT NULL REFERENCES competencia (id)
);

-- Pregunta (entidad Pregunta). Depende de factor.
CREATE TABLE pregunta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version            INTEGER       NOT NULL,
    nombre             VARCHAR(255)  NOT NULL,
    texto              VARCHAR(1000) NOT NULL,
    descripcion        VARCHAR(500),
    tipo               VARCHAR(255)  NOT NULL
                       CHECK (tipo IN ('OPCION_SIMPLE', 'OPCION_MULTIPLE')),
    fecha_modificacion TIMESTAMP(6),
    fecha_baja         DATE,
    factor_id          BIGINT        NOT NULL REFERENCES factor (id)
);

-- Opcion (entidad Opcion). La FK sale del @JoinColumn de Pregunta.opciones.
CREATE TABLE opcion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_visualizacion INTEGER      NOT NULL,
    ponderacion         INTEGER      NOT NULL,
    texto               VARCHAR(500) NOT NULL,
    pregunta_id         BIGINT       NOT NULL REFERENCES pregunta (id)
);

-- Puesto (entidad Puesto). Depende de empresa.
CREATE TABLE puesto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(255) NOT NULL UNIQUE,
    nombre      VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    empresa_id  BIGINT       NOT NULL REFERENCES empresa (id)
);

-- CaracteristicaPuesto (entidad CaracteristicaPuesto). Une puesto con competencia.
CREATE TABLE caracteristica_puesto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponderacion    INTEGER NOT NULL,
    puesto_id      BIGINT  NOT NULL REFERENCES puesto (id),
    competencia_id BIGINT  NOT NULL REFERENCES competencia (id),
    -- una competencia aparece una sola vez por puesto
    UNIQUE (puesto_id, competencia_id)
);

-- Candidato (entidad Candidato)
CREATE TABLE candidato (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_candidato    INTEGER      NOT NULL UNIQUE,
    apellido         VARCHAR(255) NOT NULL,
    nombre           VARCHAR(255) NOT NULL,
    tipo_doc         VARCHAR(255) NOT NULL
                     CHECK (tipo_doc IN ('DNI', 'LE', 'LC', 'PP')),
    nro_doc          INTEGER      NOT NULL,
    fecha_nacimiento DATE,
    genero           VARCHAR(255)
                     CHECK (genero IN ('H', 'M')),
    nacionalidad     VARCHAR(255),
    email            VARCHAR(255),
    escolaridad      VARCHAR(255)
                     CHECK (escolaridad IN ('PRIMARIO_COMPLETO', 'SECUNDARIO_COMPLETO',
                                            'UNIVERSITARIO_INCOMPLETO', 'UNIVERSITARIO_COMPLETO')),
    eliminado        BOOLEAN      NOT NULL
);

-- Evaluacion (entidad Evaluacion). Depende de puesto.
CREATE TABLE evaluacion (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                    VARCHAR(255) NOT NULL,
    fecha_creacion            DATE         NOT NULL,
    fecha_cierre              DATE,
    duracion_en_minutos       INTEGER      NOT NULL,
    cant_preguntas_por_bloque INTEGER      NOT NULL,
    puesto_id                 BIGINT       NOT NULL REFERENCES puesto (id)
);

-- Cuestionario (entidad Cuestionario). Depende de evaluacion y candidato.
CREATE TABLE cuestionario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_ingreso     VARCHAR(255) NOT NULL,
    fecha_hora_inicio TIMESTAMP(6),
    fecha_hora_fin    TIMESTAMP(6),
    ultimo_ingreso    TIMESTAMP(6),
    cantidad_accesos  INTEGER      NOT NULL,
    puntaje_total     DOUBLE PRECISION,
    estado            VARCHAR(255) NOT NULL
                      CHECK (estado IN ('ACTIVO', 'EN_PROCESO', 'COMPLETADO',
                                        'INCOMPLETO', 'SIN_CONTESTAR')),
    evaluacion_id     BIGINT       NOT NULL REFERENCES evaluacion (id),
    candidato_id      BIGINT       NOT NULL REFERENCES candidato (id)
);

-- Bloque (entidad Bloque, debil de Cuestionario). Depende de cuestionario.
CREATE TABLE bloque (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_bloque      INTEGER NOT NULL,
    cuestionario_id BIGINT  NOT NULL REFERENCES cuestionario (id),
    UNIQUE (cuestionario_id, nro_bloque)
);

-- ItemPregunta (entidad ItemPregunta, debil de Bloque). Depende de bloque y pregunta.
-- puntaje_obtenido queda en NULL hasta que se calculan los puntajes del cuestionario.
CREATE TABLE item_pregunta (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_visualizacion INTEGER NOT NULL,
    puntaje_obtenido    DOUBLE PRECISION,
    bloque_id           BIGINT  NOT NULL REFERENCES bloque (id),
    pregunta_id         BIGINT  NOT NULL REFERENCES pregunta (id)
);

-- ItemOpcion (entidad ItemOpcion, debil de ItemPregunta). Depende de item_pregunta y opcion.
CREATE TABLE item_opcion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    respondido       BOOLEAN NOT NULL,
    item_pregunta_id BIGINT  NOT NULL REFERENCES item_pregunta (id),
    opcion_id        BIGINT  NOT NULL REFERENCES opcion (id)
);

-- RegistroAuditoria (entidad RegistroAuditoria). Depende de pregunta.
CREATE TABLE registro_auditoria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_eliminacion   DATE         NOT NULL,
    hora_eliminacion    TIME(0)      NOT NULL,
    usuario_responsable VARCHAR(255) NOT NULL,
    pregunta_id         BIGINT       NOT NULL REFERENCES pregunta (id)
);
